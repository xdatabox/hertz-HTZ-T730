#!/usr/bin/env python3
"""LLM read of the attempt 1 brief (the attempt1/ folder, or the older attempt1.json) for Project Hertz. Runs after
tools/validate.py in CI.

Standard library only. Talks to the internal LiteLLM gateway (Anthropic-compatible /v1/messages behind
Cloudflare Access). Three questions, each answered with a rationale FIRST and then a verdict:

  Q1 (blocking)  the first message hands over the solution (recipe, named libraries/structures) instead of
                 stating the problem and the intended end state
  Q2 (blocking)  the task is a toy or a fresh canvas: clearly under a couple of hours of work, or not work in an
                 existing codebase
  Q3 (advisory)  the brief reads as machine-generated rather than written by the engineer who wants the work done

Verdicts are only FAIL on clear cases; borderline is PASS. Q3 never blocks. If the gateway cannot be reached or
the reply cannot be parsed, the step reports "not run" and does not block: these checks are a floor against
garbage, not the review. A human reviewer reads every brief.

Usage (CI):  python3 tools/llm_review.py attempt1 --report llm_report.md   (attempt1.json also accepted)
Env:         LITELLM_API_BASE, LITELLM_VIRTUAL_KEY, CF_ACCESS_CLIENT_ID, CF_ACCESS_CLIENT_SECRET
             optional HERTZ_QC_MODEL (default anthropic/claude-opus-5), GITHUB_* for spend tags
Exit 1 only when a blocking question fails.
"""
import argparse, json, os, re, sys, urllib.error, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))  # the orchestration runner loads this file by path
import paperwork  # noqa: E402
import codebase  # noqa: E402
DEFAULT_MODEL = "anthropic/claude-opus-5"

PROMPT = """You are a quality gate for a data project in which senior software engineers bring a real coding task
from their own work, do it with an AI coding model, and flag the model's behaviour. Before the conversation they
write a brief for a human reviewer and one "first message" that the model receives. You are reading one brief.
Answer three questions. For each, write the rationale FIRST (two or three sentences quoting the text), then the
verdict. Be conservative: answer FAIL only when the case is clear; when in doubt, PASS. A human reviewer reads
every brief after you; your job is to stop obvious garbage, not to judge quality.

Q1. Does the first message hand over the solution? FAIL if it prescribes the implementation: a numbered recipe,
the specific libraries, classes, data structures or algorithms to use, or the exact code shape. PASS if it states
the problem, the constraints and the intended end state and leaves the how to the model. Mentioning the file or
module to look at, a constraint ("standard library only"), or what to report back is fine. Requirements and
acceptance criteria (what the result must do, accept or reject, which existing behaviour must not change, what to
deliver in this increment) are the "what", not the "how": a precise, demanding first message is not a recipe.

Q2. Is this a toy task or a fresh canvas? FAIL if the task is clearly under a couple of hours of engineering for a
senior developer (a rename, a one-line fix, a config flag), or if it asks to build something from nothing rather
than change an existing codebase, or if the file list shows no real project. PASS for anything that plausibly
takes hours across several files in existing code.

Q3. Does the brief read as generated by a language model rather than written by the engineer who wants this work?
Signals: generic phrasing with no concrete file, command, number or version; symmetrical bullet lists; no
first-person stake in the outcome; explanation of what things are instead of what is wanted; the same idea
restated in each field. Counter-signals: specific paths and commands, a stated reason the work matters to this
person, uneven detail, a caveat only an insider would know. Answer SUSPECT only on strong signals; otherwise PASS.
This question is advisory and is never certain.

Return, after your rationales, exactly one JSON object on its own line:
{"q1": {"verdict": "PASS"|"FAIL", "reason": "<one sentence>"},
 "q2": {"verdict": "PASS"|"FAIL", "reason": "<one sentence>"},
 "q3": {"verdict": "PASS"|"SUSPECT", "reason": "<one sentence>"}}

--- BRIEF ---
task_description:
{task_description}

how_to_judge_completion:
{how_to_judge_completion}

reviewer_notes:
{reviewer_notes}

first_message (what the model receives):
{first_message}

tier: {tier}   codebase source: {source}

--- CODEBASE FILE LIST (first {n_files} of {total_files} paths at the pinned commit; empty if unavailable) ---
{file_list}
"""


def gateway_headers():
    h = {"content-type": "application/json", "anthropic-version": "2023-06-01",
         "x-api-key": os.environ["LITELLM_VIRTUAL_KEY"],
         "Authorization": "Bearer " + os.environ["LITELLM_VIRTUAL_KEY"]}
    cid, csec = os.environ.get("CF_ACCESS_CLIENT_ID"), os.environ.get("CF_ACCESS_CLIENT_SECRET")
    if cid and csec:
        h["CF-Access-Client-Id"] = cid; h["CF-Access-Client-Secret"] = csec
    tags = {"source": "github-actions", "surface": "quality-checks", "stage": "hertz-attempt1-llm-qc",
            "repository": os.environ.get("GITHUB_REPOSITORY", ""), "runId": os.environ.get("GITHUB_RUN_ID", ""),
            "prNumber": os.environ.get("PR_NUMBER", ""), "headSha": os.environ.get("PR_HEAD_SHA", "")}
    h["x-litellm-spend-logs-metadata"] = json.dumps({k: v for k, v in tags.items() if v})
    return h


def call_gateway(prompt):
    base = os.environ["LITELLM_API_BASE"].rstrip("/")
    model = os.environ.get("HERTZ_QC_MODEL") or DEFAULT_MODEL  # an unset GitHub variable arrives as ""
    body = json.dumps({"model": model, "max_tokens": 1500,
                       "messages": [{"role": "user", "content": prompt}]}).encode()
    last = None
    for attempt in range(3):
        try:
            req = urllib.request.Request(base + "/v1/messages", data=body, headers=gateway_headers())
            with urllib.request.urlopen(req, timeout=180) as r:
                data = json.load(r)
            return "".join(b.get("text", "") for b in data.get("content", []) if b.get("type") == "text"), None
        except urllib.error.HTTPError as e:
            body = e.read()[:300].decode(errors="replace")
            if body.lstrip().startswith("<"):  # an HTML page means the edge (Cloudflare Access) answered, not the proxy
                last = f"HTTP {e.code} from the gateway edge; the Cloudflare Access service token is missing or invalid"
            else:
                last = f"HTTP {e.code}: {body[:200]}"
            if e.code not in (429, 500, 502, 503, 529): break
        except Exception as e:
            last = f"{type(e).__name__}: {e}"
    return None, last


def parse_verdicts(text):
    """The JSON object, tolerant of a missing final brace or stray text; falls back to per-question regexes."""
    m = re.search(r"\{\s*\"q1\".*", text, re.S)
    if m:
        chunk = m.group(0).strip()
        for cand in (chunk, chunk + "}", chunk.rsplit("}", 1)[0] + "}}"):
            try:
                v = json.loads(cand)
                if all(q in v and "verdict" in v[q] for q in ("q1", "q2", "q3")):
                    for q in ("q1", "q2", "q3"):
                        v[q]["verdict"] = str(v[q]["verdict"]).upper(); v[q]["reason"] = str(v[q].get("reason", "")).strip()
                    return v
            except Exception:
                pass
    v = {}
    for q in ("q1", "q2", "q3"):
        mq = re.search(r"\"%s\"\s*:\s*\{\s*\"verdict\"\s*:\s*\"(\w+)\"\s*,\s*\"reason\"\s*:\s*\"(.*?)\"\s*\}?" % q, text, re.S)
        if not mq: return None
        v[q] = {"verdict": mq.group(1).upper(), "reason": mq.group(2).strip()}
    return v


def github_json(url):
    req = urllib.request.Request(url, headers={"Accept": "application/vnd.github+json", "User-Agent": "hertz-llm-review"})
    tok = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if tok: req.add_header("Authorization", f"Bearer {tok}")
    with urllib.request.urlopen(req, timeout=20) as r: return json.load(r)


def file_list(obj):
    """The first 150 paths of the pinned codebase (archive listing or tree), and the total count."""
    cb = obj.get("codebase") or {}
    m = re.match(r"^https://github\.com/([^/]+)/([^/]+)/pull/\d+$", cb.get("pr_url", ""))
    sha = cb.get("commit_sha", "")
    if not m or not re.fullmatch(r"[0-9a-f]{40}", sha): return [], 0
    try:
        code = codebase.load(m.group(1), m.group(2), sha)
        return code.paths[:150], len(code.paths)
    except Exception:
        return [], 0

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("file"); ap.add_argument("--report"); ap.add_argument("--no-network", action="store_true")
    a = ap.parse_args()
    src = Path(a.file)
    if not src.exists():  # the shared workflow's default is base/attempt1.json; prefer the folder next to it
        src = paperwork.resolve(src.parent, "attempt1") or src
    folder = paperwork.is_folder_format(src)
    lines = ["### Model read of " + ("`attempt1/`" if folder else "`attempt1.json`")]
    obj, problems, _ = paperwork.load(src)
    if obj is None or not isinstance(obj, dict):
        lines.append("- not run: the brief could not be read (see the format checks above); a reviewer reads the brief by hand")
        return finish(lines, a.report, 0)
    missing = [k for k in ("LITELLM_API_BASE", "LITELLM_VIRTUAL_KEY") if not os.environ.get(k)]
    if missing:
        lines.append(f"- not run: gateway credentials not configured ({', '.join(missing)}); a reviewer reads the brief by hand")
        return finish(lines, a.report, 0)
    paths, total = ([], 0) if a.no_network else file_list(obj)
    fields = {"task_description": obj.get("task_description", ""), "how_to_judge_completion": obj.get("how_to_judge_completion", ""),
              "reviewer_notes": obj.get("reviewer_notes", ""), "first_message": obj.get("first_message", ""),
              "tier": obj.get("tier", ""), "source": (obj.get("codebase") or {}).get("source", ""),
              "n_files": str(len(paths)), "total_files": str(total), "file_list": "\n".join(paths)}
    prompt = PROMPT
    for k, v in fields.items():  # plain replacement: the prompt's JSON example contains literal braces
        prompt = prompt.replace("{" + k + "}", v)
    text, err = call_gateway(prompt)
    if text is None:
        lines.append(f"- not run: could not reach the review model ({err}); a reviewer reads the brief by hand")
        return finish(lines, a.report, 0)
    v = parse_verdicts(text)
    if not v:
        lines.append("- not run: the review model's reply could not be parsed; a reviewer reads the brief by hand")
        return finish(lines, a.report, 0)
    blocking = 0
    labels = {"q1": ("attempt1/first_message.txt" if folder else "first_message", "hands over the solution"), "q2": ("task", "toy task or fresh canvas"), "q3": ("brief", "may not be written by you")}
    for q in ("q1", "q2"):
        path, what = labels[q]
        if v[q]["verdict"] == "FAIL":
            blocking += 1; lines.append(f"- BLOCKING (fix or explain) `{path}`: {what}. {v[q]['reason']} Rewrite and push to the same branch, or, if you are sure this reading is wrong for your task, explain why in a comment on this pull request; a reviewer reads the result and decides.")
        else:
            lines.append(f"- ok `{path}`: {v[q]['reason']}")
    if v["q3"]["verdict"] == "SUSPECT":
        lines.append(f"- suggestion `brief`: reads as it may not have been written by you. {v['q3']['reason']} Not blocking; the reviewer will look at authorship. Every word in the brief must be your own.")
    else:
        lines.append(f"- ok `brief`: {v['q3']['reason']}")
    return finish(lines, a.report, 1 if blocking else 0)


def finish(lines, report, code):
    print("\n".join(lines))
    if report: Path(report).write_text("\n".join(lines) + "\n")
    return code


if __name__ == "__main__":
    sys.exit(main())
